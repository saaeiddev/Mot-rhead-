import { expect, test } from '@playwright/test'
test('navigation, sound controls and preset selection', async ({ page }) => {
  await page.goto('/Mot-rhead-/')
  await expect(page.getByRole('heading', { name: /CONNECTED.*READY/ })).toBeVisible()
  await page.getByRole('button', { name: /^SOUND$/ }).click()
  await expect(page.getByRole('heading', { name: /FEEL THE.*BEAT/ })).toBeVisible()
  const firstEq = page.getByRole('slider', { name: /60 hertz equalizer gain/ })
  await expect(firstEq).toHaveValue('0')
  await firstEq.focus()
  await firstEq.press('ArrowRight')
  await expect(firstEq).not.toHaveValue('0')
  await page.getByRole('button', { name: /^PRESETS$/ }).click()
  await page.getByRole('button', { name: /BASS.*Feel every low end/i }).click()
  await page.getByRole('button', { name: /^SOUND$/ }).click()
  await expect(firstEq).toHaveValue('6')
})
test('local audio import updates player without a server upload', async ({ page }) => {
  await page.goto('/Mot-rhead-/')
  const file = Buffer.alloc(44 + 2400)
  file.write('RIFF', 0); file.writeUInt32LE(file.length - 8, 4); file.write('WAVEfmt ', 8)
  file.writeUInt32LE(16, 16); file.writeUInt16LE(1, 20); file.writeUInt16LE(1, 22)
  file.writeUInt32LE(8000, 24); file.writeUInt32LE(16000, 28)
  file.writeUInt16LE(2, 32); file.writeUInt16LE(16, 34); file.write('data', 36)
  file.writeUInt32LE(2400, 40)
  await page.locator('input[type=file]').setInputFiles({ name: 'Skate Beat.wav', mimeType: 'audio/wav', buffer: file })
  await expect(page.getByText('Skate Beat')).toBeVisible()
  await page.getByRole('button', { name: /^CONTROLS$/ }).click()
  await expect(page.getByText('Skate Beat')).toBeVisible()
})
test('mobile navigation exposes all five sections', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/Mot-rhead-/')
  await expect(page.getByRole('navigation', { name: 'Mobile navigation' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'MORE' }).click()
  await expect(page.getByRole('heading', { name: /NO LIMITS/ })).toBeVisible()
})
